import * as XLSX from 'xlsx';
import { PDFDocument, PageSizes, rgb, StandardFonts } from 'pdf-lib';

export interface ExcelToPdfOptions {
  sheetIndex?: number;
  orientation?: 'portrait' | 'landscape';
  fontSize?: number;
  title?: string;
}

export interface ParsedSpreadsheet {
  sheetNames: string[];
  activeSheetName: string;
  headers: string[];
  rows: string[][];
}

export async function parseSpreadsheetFile(file: File): Promise<ParsedSpreadsheet> {
  const arrayBuffer = await file.arrayBuffer();
  const wb = XLSX.read(arrayBuffer, { type: 'array' });
  const sheetNames = wb.SheetNames;
  const firstSheetName = sheetNames[0] || 'Sheet1';
  const ws = wb.Sheets[firstSheetName];
  const data: any[][] = XLSX.utils.sheet_to_json(ws, { header: 1 });

  const rawRows = data.filter((r) => r && r.length > 0);
  const headers = rawRows.length > 0 ? rawRows[0].map((c) => String(c ?? '')) : [];
  const rows = rawRows.length > 1 ? rawRows.slice(1).map((r) => r.map((c) => String(c ?? ''))) : [];

  return {
    sheetNames,
    activeSheetName: firstSheetName,
    headers,
    rows
  };
}

export async function convertSpreadsheetToPdf(
  headers: string[],
  rows: string[][],
  options: ExcelToPdfOptions = {}
): Promise<{ blob: Blob; pageCount: number; size: number }> {
  const pdfDoc = await PDFDocument.create();
  const font = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const boldFont = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const orientation = options.orientation || 'landscape';
  const baseDim = PageSizes.A4;
  const pageW = orientation === 'landscape' ? baseDim[1] : baseDim[0];
  const pageH = orientation === 'landscape' ? baseDim[0] : baseDim[1];

  const margin = 36;
  const usableW = pageW - margin * 2;
  const colCount = Math.max(1, headers.length);
  const colW = usableW / colCount;

  const fontSize = options.fontSize || 9;
  const rowH = 22;
  const topOffset = options.title ? margin + 30 : margin;
  const bottomOffset = margin + 20;
  const usableH = pageH - topOffset - bottomOffset;

  const rowsPerPage = Math.max(5, Math.floor(usableH / rowH) - 1); // 1 for header
  const totalPages = Math.max(1, Math.ceil(rows.length / rowsPerPage));

  for (let p = 0; p < totalPages; p++) {
    const page = pdfDoc.addPage([pageW, pageH]);
    let currentY = pageH - topOffset;

    // Header Title
    if (options.title && p === 0) {
      page.drawText(options.title, {
        x: margin,
        y: pageH - margin,
        size: 14,
        font: boldFont,
        color: rgb(0.1, 0.2, 0.5)
      });
    }

    // Table Header Row Background (Blue)
    page.drawRectangle({
      x: margin,
      y: currentY - rowH,
      width: usableW,
      height: rowH,
      color: rgb(0.92, 0.95, 0.99)
    });

    // Draw Header Text & Vertical Dividers
    for (let c = 0; c < headers.length; c++) {
      const cellX = margin + c * colW;
      const text = headers[c] || `Col ${c + 1}`;
      const truncated = text.length > 20 ? text.slice(0, 18) + '...' : text;
      page.drawText(truncated, {
        x: cellX + 4,
        y: currentY - rowH + 6,
        size: fontSize,
        font: boldFont,
        color: rgb(0.1, 0.2, 0.4)
      });
      // Header border
      page.drawRectangle({
        x: cellX,
        y: currentY - rowH,
        width: colW,
        height: rowH,
        borderWidth: 0.5,
        borderColor: rgb(0.8, 0.85, 0.9)
      });
    }

    currentY -= rowH;

    // Data rows for this page
    const pageRows = rows.slice(p * rowsPerPage, (p + 1) * rowsPerPage);

    for (let rIdx = 0; rIdx < pageRows.length; rIdx++) {
      const row = pageRows[rIdx];
      const isEven = rIdx % 2 === 0;

      // Zebra striping
      if (isEven) {
        page.drawRectangle({
          x: margin,
          y: currentY - rowH,
          width: usableW,
          height: rowH,
          color: rgb(0.98, 0.99, 1.0)
        });
      }

      for (let c = 0; c < colCount; c++) {
        const cellX = margin + c * colW;
        const cellText = row[c] || '';
        const truncated = cellText.length > 24 ? cellText.slice(0, 22) + '...' : cellText;

        page.drawText(truncated, {
          x: cellX + 4,
          y: currentY - rowH + 6,
          size: fontSize - 1,
          font,
          color: rgb(0.2, 0.2, 0.2)
        });

        // Cell border
        page.drawRectangle({
          x: cellX,
          y: currentY - rowH,
          width: colW,
          height: rowH,
          borderWidth: 0.5,
          borderColor: rgb(0.88, 0.9, 0.94)
        });
      }

      currentY -= rowH;
    }

    // Page Number Footer
    const footerText = `Page ${p + 1} of ${totalPages} • Generated by PixelKit`;
    const footerW = font.widthOfTextAtSize(footerText, 8);
    page.drawText(footerText, {
      x: (pageW - footerW) / 2,
      y: margin / 2,
      size: 8,
      font,
      color: rgb(0.5, 0.5, 0.5)
    });
  }

  const pdfBytes = await pdfDoc.save();
  const blob = new Blob([pdfBytes as any], { type: 'application/pdf' });

  return {
    blob,
    pageCount: totalPages,
    size: blob.size
  };
}
